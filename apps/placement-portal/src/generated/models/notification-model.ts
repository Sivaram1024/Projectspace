import type { Student } from './student-model';

export const NotificationNotificationTypeKeyToLabel = {
  'NotificationTypeKey0': 'Drive Announcement',
  'NotificationTypeKey1': 'Deadline Reminder',
  'NotificationTypeKey2': 'Eligibility Update',
  'NotificationTypeKey3': 'Skill Recommendation',
  'NotificationTypeKey4': 'General'
} as const;
export type NotificationNotificationTypeKey = keyof typeof NotificationNotificationTypeKeyToLabel;

export const NotificationTargetAudienceKeyToLabel = {
  'TargetAudienceKey0': 'All Students',
  'TargetAudienceKey1': 'Eligible Only',
  'TargetAudienceKey2': 'Specific Department',
  'TargetAudienceKey3': 'Specific Year'
} as const;
export type NotificationTargetAudienceKey = keyof typeof NotificationTargetAudienceKeyToLabel;

export interface Notification {
  /**
   * @displayName Notification ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Title
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  title: string;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Is Read
   * @validationRule Required for create/update operations
   */
  isRead: boolean;
  /**
   * @displayName Message
   * @validationRule Required for create/update operations
   */
  message: string;
  /**
   * @displayName Notification Type
   * @validationRule Required for create/update operations
   */
  notificationTypeKey: NotificationNotificationTypeKey;
  /**
   * @displayName Student
   */
  student?: Pick<Student, 'id' | 'name1'>;
  /**
   * @displayName Target Audience
   * @validationRule Required for create/update operations
   */
  targetAudienceKey: NotificationTargetAudienceKey;
}

export const _Notification = 'Notification' as const;
